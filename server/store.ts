// File-based case storage. Everything lives under DATA_DIR on this computer:
//   data/cases/<caseId>/case.json
//   data/cases/<caseId>/files/<storedName>
import { promises as fs } from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { type Case, emptyDetails } from "../shared/types.js";

export const DATA_DIR = path.resolve(process.env.DATA_DIR ?? "./data");
const CASES_DIR = path.join(DATA_DIR, "cases");

const ID_PATTERN = /^[a-f0-9-]{36}$/;

export function assertId(id: string): string {
  if (!ID_PATTERN.test(id)) throw new NotFoundError("Unknown id");
  return id;
}

export class NotFoundError extends Error {}

export function caseDir(caseId: string): string {
  return path.join(CASES_DIR, assertId(caseId));
}

export function filesDir(caseId: string): string {
  return path.join(caseDir(caseId), "files");
}

export function filePath(caseId: string, storedName: string): string {
  // Stored names are generated by us (uuid + extension); reject anything else.
  if (!/^[a-f0-9-]{36}(\.[a-z0-9]{1,8})?$/.test(storedName)) throw new NotFoundError("Unknown file");
  return path.join(filesDir(caseId), storedName);
}

export async function listCases(): Promise<Case[]> {
  await fs.mkdir(CASES_DIR, { recursive: true });
  const entries = await fs.readdir(CASES_DIR, { withFileTypes: true });
  const cases = await Promise.all(
    entries.filter((e) => e.isDirectory() && ID_PATTERN.test(e.name)).map((e) => getCase(e.name).catch(() => null)),
  );
  return cases
    .filter((c): c is Case => c !== null)
    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
}

export async function getCase(caseId: string): Promise<Case> {
  try {
    const raw = await fs.readFile(path.join(caseDir(caseId), "case.json"), "utf8");
    return JSON.parse(raw) as Case;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") throw new NotFoundError("Case not found");
    throw err;
  }
}

export async function saveCase(c: Case): Promise<Case> {
  c.updatedAt = new Date().toISOString();
  const dir = caseDir(c.id);
  await fs.mkdir(path.join(dir, "files"), { recursive: true });
  // Write to a temp file then rename, so a crash never leaves a half-written case.
  const tmp = path.join(dir, `case.json.${randomUUID()}.tmp`);
  await fs.writeFile(tmp, JSON.stringify(c, null, 2));
  await fs.rename(tmp, path.join(dir, "case.json"));
  return c;
}

export async function createCase(reference: string): Promise<Case> {
  const now = new Date().toISOString();
  const c: Case = {
    id: randomUUID(),
    createdAt: now,
    updatedAt: now,
    details: { ...emptyDetails(), reference },
    records: [],
    analyses: [],
  };
  return saveCase(c);
}

export async function deleteCase(caseId: string): Promise<void> {
  await fs.rm(caseDir(caseId), { recursive: true, force: true });
}

/** Simple per-case lock so concurrent requests don't overwrite each other's edits. */
const locks = new Map<string, Promise<unknown>>();
export async function withCase<T>(caseId: string, fn: (c: Case) => Promise<T> | T): Promise<T> {
  const prev = locks.get(caseId) ?? Promise.resolve();
  const run = prev.catch(() => {}).then(async () => {
    const c = await getCase(caseId);
    const result = await fn(c);
    await saveCase(c);
    return result;
  });
  locks.set(caseId, run);
  try {
    return await run;
  } finally {
    if (locks.get(caseId) === run) locks.delete(caseId);
  }
}
